-- ---------------------------------------------------------------- comments (these feed the semantic layer)
COMMENT ON SCHEMA shop IS 'Online outdoor-gear retailer: customers, products, orders, support tickets and help articles.';
COMMENT ON TABLE  shop.customers IS 'One row per registered customer.';
COMMENT ON COLUMN shop.customers.email  IS 'Customer contact email address.';
COMMENT ON COLUMN shop.customers.region IS 'Country where the customer lives.';
COMMENT ON TABLE  shop.products IS 'Catalogue of items we sell, with category and list price.';
COMMENT ON COLUMN shop.products.price IS 'List price in USD.';
COMMENT ON TABLE  shop.orders IS 'One row per customer order, with its date, total amount and lifecycle status.';
COMMENT ON COLUMN shop.orders.amount IS 'Order total in USD.';
COMMENT ON COLUMN shop.orders.status IS 'Order lifecycle state: pending, shipped, delivered, cancelled.';
COMMENT ON TABLE  shop.order_items IS 'The products inside each order, one row per product line.';
COMMENT ON TABLE  shop.support_tickets IS 'Customer support requests, open or closed.';
COMMENT ON COLUMN shop.support_tickets.status IS 'Ticket state: open or closed.';
COMMENT ON TABLE  shop.kb_articles IS 'Help-centre articles that staff and customers search for answers.';

ANALYZE shop.customers; ANALYZE shop.orders; ANALYZE shop.order_items;

