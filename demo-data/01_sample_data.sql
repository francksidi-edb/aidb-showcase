-- Every order gets at least one line item
INSERT INTO shop.order_items (order_id, product_id, quantity, unit_price)
SELECT o.id, p.id, 1 + ((o.id + p.id) % 3), p.price
FROM shop.orders o
JOIN shop.products p
  ON p.id = 1 + (o.id % 10)
  OR (o.id + p.id) % 5 = 0;

UPDATE shop.orders o
SET amount = s.total
FROM (SELECT order_id, SUM(quantity * unit_price) AS total
      FROM shop.order_items GROUP BY order_id) s
WHERE s.order_id = o.id;

