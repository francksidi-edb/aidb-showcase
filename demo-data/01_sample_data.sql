-- 01_sample_data.sql
-- "Northwind Outdoors": a small online retailer used by every Showcase step.
-- Plain Postgres only (no AIDB calls). Safe to run on any database; re-running replaces the shop schema.
-- Dates are relative to today, so "last month" always has data.

DROP SCHEMA IF EXISTS shop CASCADE;
CREATE SCHEMA shop;

-- ---------------------------------------------------------------- tables
CREATE TABLE shop.customers (
    id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      TEXT NOT NULL,
    email     TEXT NOT NULL UNIQUE,
    region    TEXT NOT NULL,
    signed_up DATE NOT NULL
);

CREATE TABLE shop.products (
    id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     TEXT NOT NULL,
    category TEXT NOT NULL,
    price    NUMERIC(10,2) NOT NULL
);

CREATE TABLE shop.orders (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INT NOT NULL REFERENCES shop.customers(id),
    order_date  DATE NOT NULL,
    status      TEXT NOT NULL,
    amount      NUMERIC(12,2) NOT NULL DEFAULT 0
);

CREATE TABLE shop.order_items (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   INT NOT NULL REFERENCES shop.orders(id),
    product_id INT NOT NULL REFERENCES shop.products(id),
    quantity   INT NOT NULL,
    unit_price NUMERIC(10,2) NOT NULL
);

CREATE TABLE shop.support_tickets (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INT NOT NULL REFERENCES shop.customers(id),
    opened_at   DATE NOT NULL,
    status      TEXT NOT NULL,
    subject     TEXT NOT NULL,
    body        TEXT NOT NULL
);

-- Help-centre articles: the documents used for "find answers by meaning".
CREATE TABLE shop.kb_articles (
    id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title    TEXT NOT NULL,
    category TEXT NOT NULL,
    body     TEXT NOT NULL
);

