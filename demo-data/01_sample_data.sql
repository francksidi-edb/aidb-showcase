-- ---------------------------------------------------------------- orders
-- Older orders: two months ago (any customer), and this month so far.
INSERT INTO shop.orders (customer_id, order_date, status)
SELECT 1 + ((g * 7) % 12),
       (date_trunc('month', current_date) - INTERVAL '2 month')::date + ((g * 3) % 27),
       (ARRAY['delivered','delivered','delivered','delivered','cancelled'])[1 + (g % 5)]
FROM generate_series(1, 25) AS g;

INSERT INTO shop.orders (customer_id, order_date, status)
SELECT 1 + ((g * 5) % 12),
       date_trunc('month', current_date)::date + (g % GREATEST(1, EXTRACT(day FROM current_date)::int)),
       (ARRAY['pending','shipped','shipped','delivered'])[1 + (g % 4)]
FROM generate_series(1, 20) AS g;

